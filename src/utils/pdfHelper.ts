/**
 * PDF generator and download helper for Biniyam's Graphic Design Portfolio
 * Creates authentic downloadable PDF documents or triggers download of uploaded PDF data URLs
 */

export function generateSimplePdfBlob(title: string, subtitle: string, bodyText: string): Blob {
  // Construct a minimal valid PDF-1.4 file
  const content = `BT
/F1 20 Tf
50 720 Td
(${escapePdfText(title)}) Tj
/F1 12 Tf
0 -30 Td
(${escapePdfText(subtitle)}) Tj
/F1 10 Tf
0 -30 Td
(${escapePdfText("Designer: Biniyam - Graphic Design Student")}) Tj
0 -20 Td
(${escapePdfText("Portfolio Document & Design Resource")}) Tj
0 -30 Td
(${escapePdfText(bodyText.slice(0, 150))}) Tj
0 -20 Td
(${escapePdfText("Verified Graphic Design Portfolio Asset - Generated by Biniyam Studio")}) Tj
ET`;

  const streamLength = content.length;

  const pdfSource = `%PDF-1.4
1 0 obj
<< /Type /Catalog /Pages 2 0 R >>
endobj
2 0 obj
<< /Type /Pages /Kids [3 0 R] /Count 1 >>
endobj
3 0 obj
<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>
endobj
4 0 obj
<< /Length ${streamLength} >>
stream
${content}
endstream
endobj
5 0 obj
<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>
endobj
xref
0 6
0000000000 65535 f 
0000000010 00000 n 
0000000059 00000 n 
0000000116 00000 n 
0000000227 00000 n 
0000000300 00000 n 
trailer
<< /Size 6 /Root 1 0 R >>
startxref
385
%%EOF`;

  return new Blob([pdfSource], { type: 'application/pdf' });
}

function escapePdfText(text: string): string {
  return text.replace(/[\\()]/g, '\\$&').replace(/[^\x20-\x7E]/g, '');
}

/**
 * Triggers browser download for a PDF document
 */
export function triggerPdfDownload(fileUrl: string, fileName: string, title: string, subtitle: string, body: string): void {
  try {
    if (fileUrl && fileUrl.startsWith('data:application/pdf')) {
      const link = document.createElement('a');
      link.href = fileUrl;
      link.download = fileName.endsWith('.pdf') ? fileName : `${fileName}.pdf`;
      document.body.appendChild(link);
      link.click();
      document.body.removeChild(link);
      return;
    }

    // Otherwise generate the actual PDF blob
    const blob = generateSimplePdfBlob(title, subtitle, body);
    const blobUrl = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = blobUrl;
    link.download = fileName.endsWith('.pdf') ? fileName : `${fileName}.pdf`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    setTimeout(() => URL.revokeObjectURL(blobUrl), 2000);
  } catch (err) {
    console.error('Download error:', err);
  }
}
